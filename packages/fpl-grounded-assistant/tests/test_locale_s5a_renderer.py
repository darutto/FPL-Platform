"""i18n S5a -- renderer.py answer text in both locales.

* ``es`` is byte-for-byte what the renderer produced before S5a: the golden file
  ``fixtures/renderer_es_golden.json`` was generated by the PRE-S5a renderer from
  the cases in ``fixtures/renderer_cases.py`` (every converted branch).
* ``en`` is real English: no Spanish markers on any line.
* The renderer holds no state: the same raw output (as a cached tool result would
  be) renders es, en, es without leaking between locales.

No network, no model call.
"""
from __future__ import annotations

import copy
import importlib.util
import json
from pathlib import Path

import pytest

from fpl_grounded_assistant.renderer import render

_HERE = Path(__file__).resolve().parent


def _load(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


CASES = _load(_HERE / "fixtures" / "renderer_cases.py", "renderer_cases").CASES
GOLDEN = json.loads((_HERE / "fixtures" / "renderer_es_golden.json").read_text(encoding="utf-8"))
_ratchet = _load(_HERE.parent / "scripts" / "i18n_literal_ratchet.py", "i18n_literal_ratchet_s5a")

IDS = [name for name, _, _ in CASES]

#: Cases whose text is identical in both locales: a message the TOOL wrote (passed
#: through verbatim), and a sentence that was English-only before S5a and is left
#: alone on purpose (no new Spanish was invented for it).
_SAME_IN_BOTH: set[str] = {"team_results_ambiguous_msg", "find_players_empty"}


def test_golden_covers_every_case():
    assert set(GOLDEN) == set(IDS)


@pytest.mark.parametrize("name,tool,payload", CASES, ids=IDS)
def test_es_is_byte_identical_to_the_pre_s5a_renderer(name, tool, payload):
    assert render(tool, copy.deepcopy(payload), locale="es") == GOLDEN[name]
    # the default locale is es
    assert render(tool, copy.deepcopy(payload)) == GOLDEN[name]


@pytest.mark.parametrize("name,tool,payload", CASES, ids=IDS)
def test_en_has_no_spanish_left(name, tool, payload):
    text = render(tool, copy.deepcopy(payload), locale="en")
    assert text and text != GOLDEN[name] or name in _SAME_IN_BOTH, name
    for line in text.splitlines():
        assert not _ratchet._looks_spanish(line), (name, line)


def test_same_raw_output_renders_each_locale_without_leaking():
    raw = {
        "status": "ok", "current_gw": 8, "current_gw_status": "in progress", "next_gw": 9,
        "blank_gw_alerts": [], "double_gw_alerts": [{"gw": 11, "double_teams": ["CHE"]}],
    }
    es1 = render("get_gameweek_context", raw, locale="es")
    en = render("get_gameweek_context", raw, locale="en")
    es2 = render("get_gameweek_context", raw, locale="es")
    assert es1 == es2 != en
    assert es1.startswith("Jornada actual: GW8")
    assert en.startswith("Current gameweek: GW8")
    assert raw["current_gw"] == 8  # the raw output is never mutated


def test_rank_captain_english_no_longer_leaks_spanish_labels():
    """EN used to print «Conviene saber:» / «Sobre X:» (the only Spanish-only pair)."""
    from fpl_grounded_assistant import catalogue

    assert catalogue.t("renderer.captain.worth_knowing", "en", line="L") == "Worth knowing: L"
    assert catalogue.t("renderer.captain.about", "en", name="N", note="n") == "On N: n"
    assert catalogue.t("renderer.captain.worth_knowing", "es", line="L") == "Conviene saber: L"
